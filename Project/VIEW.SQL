CREATE VIEW VW_RESUME_SALES AS
    SELECT S.ID
         , S.DATE_SALES
         , C.NAME AS CUSTOMER_NAME
         , P.NAME AS PRODUCT_NAME
         , I.QUANTITY
         , I.UNIT_PRICE
         , (I.QUANTITY * I.UNIT_PRICE) AS SUBTOTAL
         , S.TOTAL
         , S.STATUS
    FROM CUSTOMERS C
    INNER JOIN SALES S ON C.ID = S.ID_CUSTOMER
    INNER JOIN ITEMS I ON S.ID = I.ID_SALE
    INNER JOIN PRODUCTS P ON I.ID_PRODUCT = P.ID

SELECT * FROM VW_RESUME_SALES