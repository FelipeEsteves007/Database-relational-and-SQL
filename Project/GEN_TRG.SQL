CREATE SEQUENCE PRODUCT;
CREATE SEQUENCE INVENTORY;
CREATE SEQUENCE ITEM;
CREATE SEQUENCE SALE;
CREATE SEQUENCE CUSTOMER;

CREATE OR ALTER TRIGGER TRG_PRODUCT_BF FOR PRODUCTS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ID IS NULL) THEN
      NEW.ID = GEN_ID(PRODUCT,1);
END;

