SELECT P.NAME
     , SUM(I.QUANTITY * I.UNIT_PRICE) AS SALE_TOTAL
FROM ITEMS I
INNER JOIN PRODUCTS P ON I.ID_PRODUCT = P.ID
GROUP BY 1
HAVING SUM(I.QUANTITY * I.UNIT_PRICE) > 10

SELECT P.NAME
     , P.SALE_PRICE
FROM PRODUCTS P
WHERE P.SALE_PRICE IN (SELECT MAX(SALE_PRICE) FROM PRODUCTS)

WITH AVERAGE AS(
    SELECT C.NAME
         , SUM(S.TOTAL) AS TOTAL
    FROM CUSTOMERS C
    INNER JOIN SALES S ON C.ID = S.ID_CUSTOMER
    GROUP BY 1
)

SELECT AVG(TOTAL) AS AVG_TOTAL
FROM AVERAGE

SELECT FIRST 5 P.NAME
FROM ITEMS S
INNER JOIN PRODUCTS P ON S.ID_PRODUCT = P.ID
ORDER BY S.QUANTITY DESC

SELECT FIRST 5 P.NAME
     , SUM(S.QUANTITY) AS  MAX_QTD
FROM ITEMS S
INNER JOIN PRODUCTS P ON S.ID_PRODUCT = P.ID
GROUP BY 1
ORDER BY 2 DESC

