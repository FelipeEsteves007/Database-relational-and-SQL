SELECT *
FROM PRODUCTS P
WHERE P.NAME LIKE 'M%'

SELECT *
FROM PRODUCTS P
WHERE P.SALE_PRICE BETWEEN 50.00 AND 100.00

SELECT EXTRACT (DAY FROM S.DATE_SALES) AS DAY_SALE
     , EXTRACT (MONTH FROM S.DATE_SALES) AS MONTH_SALE
     , EXTRACT (YEAR FROM S.DATE_SALES) AS YEAR_SALE
     , CASE
        WHEN S.TOTAL < 50 THEN 'CHEAP'
        WHEN S.TOTAL BETWEEN 50 AND 100 THEN 'AVERAGE VALUE'
        ELSE 'EXPENSIVE'
       END AS CLASSIFICATION
FROM SALES S

SELECT C.NAME
     , COALESCE(S.TOTAL,'NO SALE')
FROM CUSTOMERS C
LEFT JOIN SALES S ON C.ID = S.ID_CUSTOMER

SELECT C.NAME AS CUSTOMER_NAME
     , P.NAME AS PRODUCT_NAME
     , S.ID
     , S.TOTAL
     , I.QUANTITY
     , I.UNIT_PRICE
FROM SALES S
INNER JOIN CUSTOMERS C ON S.ID_CUSTOMER = C.ID
INNER JOIN ITEMS I ON S.ID = I.ID_SALE
INNER JOIN PRODUCTS P ON I.ID_PRODUCT = P.ID

