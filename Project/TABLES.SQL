CREATE TABLE CUSTOMERS (
    ID INTEGER PRIMARY KEY NOT NULL,
    NAME  VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100),
    DATE_CREATION DATE, 
    STATUS VARCHAR(1) DEFAULT 'A'
    -- I INACTUVE A ACTIVE
)

CREATE TABLE PRODUCTS (
    ID INTEGER PRIMARY KEY NOT NULL,
    NAME  VARCHAR(50) NOT NULL,
    COST_PRICE NUMERIC(10,2) NOT NULL,
    SALE_PRICE NUMERIC(10,2) NOT NULL,
    STOCK NUMERIC(10,2) NOT NULL,
    MIN_STOCK NUMERIC(10,2)
)

CREATE TABLE SALES (
    ID INTEGER PRIMARY KEY NOT NULL,
    ID_CUSTOMER INTEGER NOT NULL,
    DATE_SALES DATE,
    TOTAL NUMERIC(10,2) NOT NULL,
    STATUS VARCHAR(1) DEFAULT 'A',
    -- A APPROVED C CANCEL
    CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (ID_CUSTOMER)
    REFERENCES CUSTOMERS(ID)
)

CREATE TABLE ITEMS (
    ID INTEGER PRIMARY KEY NOT NULL,
    ID_SALE INTEGER NOT NULL,
    ID_PRODUCT INTEGER NOT NULL,
    QUANTITY NUMERIC(10,2),
    UNIT_PRICE NUMERIC(10,2),

    CONSTRAINT FK_ITEMS_SALES FOREIGN KEY (ID_SALE)
    REFERENCES SALES(ID),
    CONSTRAINT FK_ITEMS_PRODUCTS FOREIGN KEY (ID_PRODUCT)
    REFERENCES PRODUCTS(ID)
)

CREATE TABLE INVENTORY_AUDIT (
    ID INTEGER PRIMARY KEY NOT NULL,
    ID_PRODUCT INTEGER NOT NULL,
    TYPE VARCHAR(1) DEFAULT 'I',
    /* I INFLOW O OUTFLOW */
    PREVIOUS_QUANTITY NUMERIC(10,2),
    NEW_QUANTITY NUMERIC(10,2),
    DATE_INVENTORY DATE,
    USER_RESPONSIBLE VARCHAR(50),

    CONSTRAINT FK_INVENTORY_PRODUCTS FOREIGN KEY (ID_PRODUCT)
    REFERENCES PRODUCTS(ID)
)