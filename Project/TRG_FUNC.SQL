CREATE OR ALTER TRIGGER TRG_PRODUCT_BU FOR PRODUCTS
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    BEGIN
        IF(OLD.STOCK <> NEW.STOCK) THEN
        BEGIN
            INSERT INTO INVENTORY_AUDIT(ID_PRODUCT,TYPE,PREVIOUS_QUANTITY,NEW_QUANTITY,DATE_INVENTORY,USER_RESPONSIBLE)
            VALUES(NEW.ID,'A',OLD.STOCK, NEW.STOCK,CURRENT_TIMESTAMP,CURRENT_USER);
        END
    END
END;

CREATE OR ALTER FUNCTION FN_STOCK_TOTAL (
    ID INTEGER)
RETURNS NUMERIC(10,2)
AS
DECLARE VARIABLE V_PRICE NUMERIC(10,2);
DECLARE VARIABLE V_STOCK INTEGER;
BEGIN
  SELECT P.STOCK, P.SALE_PRICE
  FROM PRODUCTS P
  WHERE P.ID = :ID
  INTO :V_STOCK, :V_PRICE;

  RETURN COALESCE(:V_STOCK, 0) * COALESCE(:V_PRICE, 0);
END;

SELECT P.ID, P.NAME, P.COST_PRICE, P.SALE_PRICE, P.STOCK, P.MIN_STOCK, FN_STOCK_TOTAL(P.ID)
FROM PRODUCTS P

