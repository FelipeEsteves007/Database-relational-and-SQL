CREATE OR ALTER EXCEPTION STOCK_MAX 'THE PRODUCT IS OUT OF STOCK';

CREATE PROCEDURE CALC_ORDER (
    P_ID_PRODUCT INTEGER,
    P_QUANTITY INTEGER
)
RETURNS (
    V_SUBTOTAL NUMERIC(10,2)
)
AS
    DECLARE VARIABLE V_SALES_PRICE NUMERIC(10,2);
    DECLARE VARIABLE V_STOCK INTEGER;
BEGIN
    SELECT P.STOCK, P.SALE_PRICE
    FROM PRODUCTS P
    WHERE P.ID = :P_ID_PRODUCT
    INTO :V_STOCK, :V_SALES_PRICE;

    IF (V_STOCK < P_QUANTITY) THEN
    BEGIN
        EXCEPTION STOCK_MAX;
    END
    ELSE
    BEGIN
        V_SUBTOTAL = P_QUANTITY * V_SALES_PRICE;
    END
            
    SUSPEND;
END;

SELECT V_SUBTOTAL FROM CALC_ORDER(1,30)