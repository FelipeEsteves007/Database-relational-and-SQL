EXECUTE BLOCK
RETURNS (
    P_IDPRODUCT INTEGER,
    P_SUBTOTAL NUMERIC(10,2),
    P_MESSAGE VARCHAR(30)
)
AS
    DECLARE VARIABLE V_ID INTEGER;
    DECLARE VARIABLE V_QTY INTEGER = 9;
BEGIN
    FOR SELECT P.ID
    FROM PRODUCTS P
    INTO :V_ID

    DO
    BEGIN
    P_IDPRODUCT = :V_ID;

    EXECUTE PROCEDURE CALC_ORDER(:V_ID, :V_QTY) RETURNING_VALUES :P_SUBTOTAL;
    P_MESSAGE = 'OK';
    SUSPEND;
    
    WHEN EXCEPTION STOCK_MAX DO
    BEGIN
        P_MESSAGE = 'NOT OK';
        P_SUBTOTAL = 0.00;
        SUSPEND;
    END
    END
END