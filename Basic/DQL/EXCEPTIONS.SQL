ALTER TABLE PRODUCT ADD MAX_STOCK INTEGER;

CREATE EXCEPTION EX_STOCK_LIMIT 'STOCK EXCEEDS PERMITTED LIMIT'

CREATE OR ALTER TRIGGER TRG_PRODUCT_STOCK_UPDATESORINSERT FOR PRODUCT
ACTIVE BEFORE INSERT OR UPDATE POSITION 1
AS
BEGIN
    IF (NEW.MAX_STOCK > 1000) THEN
    BEGIN   
        EXCEPTION EX_STOCK_LIMIT;
    END    
END;