CREATE EXCEPTION EX_INVALID_PRICE 'The product price must not be less than 0'

CREATE OR ALTER TRIGGER TRG_PRODUCT_UPDATEORINSERT FOR PRODUCT
ACTIVE BEFORE INSERT OR UPDATE POSITiON 0
AS
BEGIN
    IF (NEW.PRICE < 0) THEN
    BEGIN   
        EXCEPTION EX_INVALID_PRICE;
    END
END;

