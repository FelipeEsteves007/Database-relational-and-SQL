-- 1
SELECT P.DESCRIPTION
FROM PRODUCT P
WHERE P.ID_CATEGORY IN (SELECT C.ID_CATEGORY FROM CATEGORY C WHERE C.NAME_CATEGORY LIKE '%A%')

-- 2
SELECT S.LEGAL_NAME
FROM SUPPLIER S
WHERE EXISTS (SELECT P.ID_SUPPLIER FROM PRODUCT P WHERE P.ID_SUPPLIER = S.ID_SUPPLIER)

-- 3
SELECT P.DESCRIPTION
FROM PRODUCT P
WHERE NOT EXISTS (SELECT 1 FROM SALES_ITEMS SI WHERE P.ID_PRODUCT = SI.ID_PRODUCT)

-- 4
SELECT P.DESCRIPTION
     , P.PRICE
FROM PRODUCT P
WHERE P.PRICE > (SELECT AVG(PE.PRICE) FROM PRODUCT PE )

--5
SELECT C.NAME_CATEGORY
FROM CATEGORY C
WHERE C.ID_CATEGORY IN (SELECT P.ID_CATEGORY FROM PRODUCT P)
AND C.ID_CATEGORY NOT IN (SELECT P.ID_CATEGORY FROM SALES_ITEMS S INNER JOIN PRODUCT P ON S.ID_PRODUCT = P.ID_PRODUCT)