-- 1
SELECT P.DESCRIPTION
FROM PRODUCT P
WHERE P.ID_CATEGORY IN (SELECT C.ID_CATEGORY FROM CATEGORY C WHERE C.NAME_CATEGORY LIKE '%A%')

-- 2
SELECT S.LEGAL_NAME
FROM SUPPLIER S
WHERE EXISTS (SELECT P.ID_SUPPLIER FROM PRODUCT P WHERE P.ID_SUPPLIER = S.ID_SUPPLIER)

-- 3
SELECT P.DESCRIPTION
FROM PRODUCT P
WHERE NOT EXISTS (SELECT 1 FROM SALES_ITEMS SI WHERE P.ID_PRODUCT = SI.ID_PRODUCT)

-- 4
SELECT P.DESCRIPTION
     , P.PRICE
FROM PRODUCT P
WHERE P.PRICE > (SELECT AVG(PE.PRICE) FROM PRODUCT PE )

--5
SELECT C.NAME_CATEGORY
FROM CATEGORY C
WHERE C.ID_CATEGORY IN (SELECT P.ID_CATEGORY FROM PRODUCT P)
AND C.ID_CATEGORY NOT IN (SELECT P.ID_CATEGORY FROM SALES_ITEMS S INNER JOIN PRODUCT P ON S.ID_PRODUCT = P.ID_PRODUCT)

-- 6
SELECT P.DESCRIPTION
     , P.PRICE
     , (SELECT AVG(PE.PRICE) FROM PRODUCT PE) AS MEDIDA
FROM PRODUCT P

-- 7
SELECT C.NAME_CATEGORY
     , (SELECT COUNT(P.ID_PRODUCT) FROM PRODUCT P WHERE C.ID_CATEGORY = P.ID_CATEGORY) AS PRODUCTS
FROM CATEGORY C

-- 8
SELECT S.LEGAL_NAME
     , (SELECT COUNT(P.ID_PRODUCT) FROM PRODUCT P WHERE S.ID_SUPPLIER = P.ID_SUPPLIER) AS PRODUCTS
FROM SUPPLIER S

-- 9
SELECT V.ID_CATEGORY
FROM (SELECT P.ID_CATEGORY
           , AVG(P.PRICE) AS AV
      FROM PRODUCT P
      GROUP BY P.ID_CATEGORY) AS V
WHERE V.AV > 5

-- 10
-- HAVING
SELECT C.NAME_CATEGORY
     , MAX(P.PRICE) AS MAXPRICE
FROM CATEGORY C
JOIN PRODUCT P ON C.ID_CATEGORY = P.ID_CATEGORY
GROUP BY 1
HAVING MAX(P.PRICE) > 100

-- SUBSELECT
SELECT C.NAME_CATEGORY
     , M.MAXPRICE
FROM (SELECT P.id_category
           , MAX(P.PRICE) AS MAXPRICE
      FROM PRODUCT P
      GROUP BY 1) AS M
INNER JOIN CATEGORY C ON M.id_category = C.ID_CATEGORY
WHERE M.MAXPRICE > 100