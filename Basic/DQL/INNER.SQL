-- 1
SELECT P.DESCRIPTION
     , C.NAME_CATEGORY
FROM PRODUCT P
INNER JOIN CATEGORY C ON C.ID_CATEGORY = P.ID_CATEGORY

-- 2
SELECT PR.DESCRIPTION
     , S.LEGAL_NAME
FROM PRODUCT PR
INNER JOIN SUPPLIER S ON S.ID_SUPPLIER = PR.ID_SUPPLIER
WHERE PR.PRICE > 0

-- 3
SELECT PRO.DESCRIPTION
     , CA.NAME_CATEGORY
     , SA.QUANTITY
FROM PRODUCT PRO
INNER JOIN CATEGORY CA ON CA.ID_CATEGORY = PRO.ID_CATEGORY
INNER JOIN SALES_ITEMS SA ON SA.ID_PRODUCT = PRO.ID_PRODUCT

-- 4
SELECT CAT.NAME_CATEGORY
     , COUNT(PROD.ID_PRODUCT) AS TOTAL_PROD
FROM CATEGORY CAT
INNER JOIN PRODUCT PROD ON PROD.ID_CATEGORY = CAT.ID_CATEGORY
GROUP BY CAT.NAME_CATEGORY

-- 5
SELECT PE.DESCRIPTION
     , SUM(SIT.QUANTITY * SIT.UNIT_PRICE) AS TOTAL_SALES
     , SUM(SIT.QUANTITY)
FROM PRODUCT PE
INNER JOIN SALES_ITEMS SIT ON SIT.ID_PRODUCT = PE.ID_PRODUCT
GROUP BY PE.DESCRIPTION
HAVING SUM(SIT.QUANTITY * SIT.UNIT_PRICE) > 2
ORDER BY TOTAL_SALES DESC
