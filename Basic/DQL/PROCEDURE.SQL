CREATE OR ALTER PROCEDURE SP_APPLY_DISCOUNT (
    P_ID_PRODUT INTEGER,
    P_PERCENTAGE NUMERIC(10,2)
)
RETURNS (
    V_NEW_PRICE NUMERIC(10,2)
)
AS BEGIN

    SELECT P.PRICE
    FROM PRODUCT P
    WHERE P.ID_PRODUCT = :P_ID_PRODUT
    INTO :V_NEW_PRICE;

    IF (P_PERCENTAGE > 50) THEN
    BEGIN
        V_NEW_PRICE = V_NEW_PRICE - (V_NEW_PRICE * 0.50);
    END
    ELSE
    BEGIN
        IF (P_PERCENTAGE <= 50) THEN
        BEGIN
            V_NEW_PRICE = V_NEW_PRICE - (V_NEW_PRICE * (:P_PERCENTAGE/100));
        END
    END

    SUSPEND;
END;

SELECT V_NEW_PRICE FROM SP_APPLY_DISCOUNT(1,90.0)