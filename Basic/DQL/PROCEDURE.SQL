CREATE OR ALTER PROCEDURE SP_CALCULATE_STOCK_VALUE (
    P_ID_PRODUCT INTEGER
)
RETURNS (
    V_TOTAL_STOCK_VALUE NUMERIC(10,2)
)
AS
BEGIN
    SELECT (P.PRICE * P.MIN_STOCK) AS TOTAL
    FROM PRODUCT P
    WHERE P.ID_PRODUCT = :P_ID_PRODUCT
    INTO :V_TOTAL_STOCK_VALUE;

    SUSPEND;
END;

SELECT V_TOTAL_STOCK_VALUE FROM SP_CALCULATE_STOCK_VALUE(1)

