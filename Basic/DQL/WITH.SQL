-- 1
WITH MAXPRICE AS(
    SELECT P.ID_CATEGORY
         , MAX(P.PRICE) AS PRICEMAX
    FROM PRODUCT P
    GROUP BY P.ID_CATEGORY
)

SELECT M.ID_CATEGORY
FROM MAXPRICE M
WHERE M.PRICEMAX > 100

-- 2
WITH MAXPRICE AS(
    SELECT P.ID_CATEGORY
         , MAX(P.PRICE) AS PRICEMAX
    FROM PRODUCT P
    GROUP BY P.ID_CATEGORY
)

SELECT C.NAME_CATEGORY
FROM MAXPRICE M
INNER JOIN CATEGORY C ON M.ID_CATEGORY = C.ID_CATEGORY
WHERE M.PRICEMAX > 100

-- 3
WITH MAXCATEGORY AS(
   SELECT P.ID_CATEGORY
    , MAX(P.PRICE) AS PRICEMAX
   FROM PRODUCT P
   GROUP BY P.ID_CATEGORY
),
AVGCATEGORY AS (
    SELECT PE.ID_CATEGORY
        , AVG(PE.PRICE) AS PRICEAVG
    FROM PRODUCT PE
    GROUP BY PE.ID_CATEGORY
)

SELECT C.NAME_CATEGORY
    , M.PRICEMAX
    , A.PRICEAVG
FROM MAXCATEGORY M
INNER JOIN CATEGORY C ON M.ID_CATEGORY = C.ID_CATEGORY
INNER JOIN AVGCATEGORY A ON C.ID_CATEGORY = A.ID_CATEGORY

-- 4
WITH TOTSALE AS (
    SELECT S.ID_PRODUCT
         , SUM(S.QUANTITY * S.UNIT_PRICE) AS TOTAL
    FROM SALES_ITEMS S
    GROUP BY S.ID_PRODUCT
)

SELECT P.DESCRIPTION
     , T.TOTAL
FROM TOTSALE T
INNER JOIN PRODUCT P ON T.ID_PRODUCT = P.ID_PRODUCT

-- 5

WITH PROD AS (
    SELECT P.ID_CATEGORY
         , S.ID_PRODUCT
         , SUM(S.QUANTITY * S.UNIT_PRICE) AS SUBTOTAL
    FROM SALES_ITEMS S
    INNER JOIN PRODUCT P ON S.ID_PRODUCT = P.ID_PRODUCT
    GROUP BY 1, 2
),
CATE AS (
    SELECT PR.ID_CATEGORY
         , MAX(PR.SUBTOTAL) AS MAX_SUBTOTAL
    FROM PROD PR
    GROUP BY 1
)

SELECT CA.NAME_CATEGORY
     , T.DESCRIPTION
     , C.MAX_SUBTOTAL
FROM CATE C
INNER JOIN CATEGORY CA ON C.ID_CATEGORY = CA.ID_CATEGORY
INNER JOIN PROD P ON C.ID_CATEGORY = P.ID_CATEGORY AND C.MAX_SUBTOTAL = P.SUBTOTAL
INNER JOIN PRODUCT T ON P.ID_PRODUCT = T.ID_PRODUCT