-- 1
CREATE OR ALTER TRIGGER TRG_PRODUCT_BU FOR PRODUCT
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    IF (NEW.DESCRIPTION IS NULL OR TRIM(NEW.DESCRIPTION) = '' ) THEN
    BEGIN
        NEW.DESCRIPTION = OLD.DESCRIPTION;
    END
END;

-- 2
CREATE EXCEPTION EX_MIN_STOCK 'ERROR - STOCK GREATER THAN 0'

CREATE OR ALTER TRIGGER TRG_PRODUCT_AUDIT_LOG FOR PRODUCT
ACTIVE BEFORE INSERT OR DELETE POSITION 0
AS
BEGIN
    IF (INSERTING) THEN
    BEGIN
        IF (NEW.DESCRIPTION IS NULL OR NEW.DESCRIPTION = '') THEN
        BEGIN
          NEW.DESCRIPTION = 'NO NAME';
        END 
    END

    IF (DELETING) THEN
    BEGIN
        IF (OLD.MIN_STOCK > 0) THEN
        BEGIN
            EXCEPTION EX_MIN_STOCK;
        END 
    END
END;