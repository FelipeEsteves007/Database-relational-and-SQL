CREATE OR ALTER TRIGGER TRG_PRODUCT_BU FOR PRODUCT
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    IF (NEW.DESCRIPTION IS NULL OR TRIM(NEW.DESCRIPTION) = '' ) THEN
    BEGIN
        NEW.DESCRIPTION = OLD.DESCRIPTION;
    END
END;

-- 2
CREATE EXCEPTION EX_MIN_STOCK 'ERROR - STOCK GREATER THAN 0'

CREATE OR ALTER TRIGGER TRG_PRODUCT_AUDIT_LOG FOR PRODUCT
ACTIVE BEFORE INSERT OR DELETE POSITION 0
AS
BEGIN
    IF (INSERTING) THEN
    BEGIN
        IF (NEW.DESCRIPTION IS NULL OR NEW.DESCRIPTION = '') THEN
        BEGIN
          NEW.DESCRIPTION = 'NO NAME';
        END 
    END

    IF (DELETING) THEN
    BEGIN
        IF (OLD.MIN_STOCK > 0) THEN
        BEGIN
            EXCEPTION EX_MIN_STOCK;
        END 
    END
END;

-- 3
CREATE TABLE PRODUCT_LOG (
    ID_PRODUCT INTEGER,
    OLD_PRICE NUMERIC(10,2),
    NEW_PRICE NUMERIC(10,2),
    DATES TIMESTAMP
)

CREATE OR ALTER TRIGGER TRG_PRODUCT_UPDATE FOR PRODUCT
ACTIVE AFTER UPDATE POSITION 0
AS
BEGIN
    IF (UPDATING) THEN
    BEGIN
        IF (OLD.PRICE <> NEW.PRICE) THEN
        BEGIN
            INSERT INTO PRODUCT_LOG(ID_PRODUCT, OLD_PRICE, NEW_PRICE, DATES)
            VALUES (NEW.ID_PRODUCT, OLD.PRICE, NEW.PRICE, CURRENT_TIMESTAMP);
        END
    END
END;

