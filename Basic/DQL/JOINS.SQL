-- 1
SELECT P.DESCRIPTION
     , (S.QUANTITY * S.UNIT_PRICE) AS SUBTOTAL
     , C.NAME_CATEGORY
FROM PRODUCT P
INNER JOIN SALES_ITEMS S ON P.ID_PRODUCT = S.ID_PRODUCT
INNER JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY

-- 2
SELECT P.DESCRIPTION
     , C.NAME_CATEGORY
     , S.LEGAL_NAME
FROM PRODUCT P
INNER JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY
INNER JOIN SUPPLIER S ON P.ID_SUPPLIER = S.ID_SUPPLIER
WHERE P.PRICE > 0

-- 3
SELECT SI.ID_PRODUCT
     , P.DESCRIPTION
     , C.NAME_CATEGORY
     , S.LEGAL_NAME
FROM SALES_ITEMS SI
INNER JOIN PRODUCT P ON SI.ID_PRODUCT = P.ID_PRODUCT
INNER JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY
INNER JOIN SUPPLIER S ON P.ID_SUPPLIER = S.ID_SUPPLIER

-- 4
SELECT P.DESCRIPTION
     , C.NAME_CATEGORY
     , S.QUANTITY AS QTD_SALE
FROM PRODUCT P
INNER JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY
LEFT JOIN SALES_ITEMS S ON P.ID_PRODUCT = S.ID_PRODUCT

-- 5
SELECT C.NAME_CATEGORY
     , S.LEGAL_NAME
     , SUM(SE.QUANTITY) AS TOTAL_ITEMS
     , SUM(SE.UNIT_PRICE * SE.QUANTITY) AS SUBTOTAL
FROM PRODUCT P
INNER JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY
INNER JOIN SUPPLIER S ON P.ID_SUPPLIER = S.ID_SUPPLIER
INNER JOIN SALES_ITEMS SE ON P.ID_PRODUCT = SE.ID_PRODUCT
GROUP BY C.NAME_CATEGORY, S.LEGAL_NAME
HAVING SUM(SE.UNIT_PRICE * SE.QUANTITY) > 5
ORDER BY SUBTOTAL DESC