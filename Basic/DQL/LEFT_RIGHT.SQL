-- 1
SELECT C.NAME_CATEGORY
     , P.DESCRIPTION
FROM CATEGORY C
LEFT JOIN PRODUCT P ON C.ID_CATEGORY = P.ID_CATEGORY

-- 2
SELECT PR.DESCRIPTION
     , S.QUANTITY
FROM PRODUCT PR
LEFT JOIN SALES_ITEMS S ON PR.ID_PRODUCT = S.ID_PRODUCT

-- 3
SELECT PRO.DESCRIPTION
FROM PRODUCT PRO
LEFT JOIN SALES_ITEMS SA ON PRO.ID_PRODUCT = SA.ID_PRODUCT
WHERE SA.ID_PRODUCT IS NULL

-- 4
SELECT SU.LEGAL_NAME
     , PROD.DESCRIPTION
FROM PRODUCT PROD
RIGHT JOIN SUPPLIER SU ON PROD.ID_SUPPLIER = SU.ID_SUPPLIER

-- 5
SELECT PT.DESCRIPTION
     , SUM(ST.QUANTITY) AS TOTAL
FROM PRODUCT PT
LEFT JOIN SALES_ITEMS ST ON PT.ID_PRODUCT = ST.ID_PRODUCT
GROUP BY PT.DESCRIPTION
ORDER BY TOTAL DESC