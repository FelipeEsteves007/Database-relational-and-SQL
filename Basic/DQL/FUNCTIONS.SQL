SELECT AVG(WAGE) AS AVG_WAGE,
       MIN(WAGE) AS MIN_WAGE,
       MAX(WAGE) AS MAX_WAGE
FROM EMPLOYEE
WHERE DATE_HIRE > '2025-01-01'

