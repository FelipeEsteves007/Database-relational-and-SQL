SELECT MAX(SI.UNIT_PRICE) AS MAX_UNIT_PRICE,
       SUM(SI.QUANTITY * SI.UNIT_PRICE) AS TOTAL
FROM SALES_ITEMS SI
WHERE SI.ID_PRODUCT <> 3

-- 4
ALTER TABLE PRODUCT ADD PRICE DECIMAL(10,2)

UPDATE PRODUCT
    SET PRICE = '10'
WHERE ID_PRODUCT = 1

UPDATE PRODUCT
    SET PRICE = '5'
WHERE ID_PRODUCT = 3

UPDATE PRODUCT
    SET PRICE = '7'
WHERE ID_PRODUCT = 4

SELECT COUNT(P.ID_PRODUCT) AS COUNT_PROD,
       AVG(P.PRICE) AS AVG_PRICE
FROM PRODUCT P
WHERE P.MIN_STOCK > 0

