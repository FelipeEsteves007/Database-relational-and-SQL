DELETE FROM SALES_ITEMS S
    WHERE S.QUANTITY = 1 AND S.UNIT_PRICE < 2

SELECT FIRST 2 P.PRICE,
       P.DESCRIPTION
FROM PRODUCT P
WHERE P.DESCRIPTION LIKE '%S%' OR P.DESCRIPTION LIKE '%T%'
ORDER BY PRICE DESC