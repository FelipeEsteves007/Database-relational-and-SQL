-- 1
SELECT P.ID_CATEGORY
     , COUNT (P.ID_PRODUCT) AS TOTAL
FROM PRODUCT P
GROUP BY P.ID_CATEGORY

-- 2
SELECT PR.ID_CATEGORY
     , AVG(PR.PRICE) AS AVERAGE
FROM PRODUCT PR
GROUP BY PR.ID_CATEGORY
ORDER BY AVERAGE DESC

-- 3
SELECT PO.ID_CATEGORY
     , COUNT(PO.ID_PRODUCT) AS TOTAL
FROM PRODUCT PO
GROUP BY PO.ID_CATEGORY
HAVING COUNT (*) > 1

-- 4
SELECT S.ID_PRODUCT
     , SUM(S.QUANTITY) AS SUM_QUANTITY
FROM SALES_ITEMS S
GROUP BY S.ID_PRODUCT
ORDER BY SUM_QUANTITY DESC

-- 5
SELECT SI.ID_PRODUCT
     , COUNT(SI.QUANTITY) AS SALES_TOTAL
     , SUM(SI.QUANTITY * SI.UNIT_PRICE) AS TOTAL
FROM SALES_ITEMS SI
WHERE SI.UNIT_PRICE > 1
GROUP BY SI.ID_PRODUCT
HAVING SUM(SI.QUANTITY * SI.UNIT_PRICE) > 2
ORDER BY TOTAL DESC
