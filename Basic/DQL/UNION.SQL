-- 1
SELECT P.DESCRIPTION
FROM PRODUCT P
UNION -- (Distinct)
SELECT C.NAME_CATEGORY
FROM CATEGORY C

-- 2
SELECT P.DESCRIPTION
FROM PRODUCT P
UNION ALL
SELECT C.NAME_CATEGORY
FROM CATEGORY C

-- 3
SELECT P.ID_PRODUCT
FROM PRODUCT P
INTERSECT
SELECT S.ID_PRODUCT
FROM SALES_ITEMS S
WHERE S.QUANTITY > 0

-- 4
SELECT P.ID_PRODUCT
FROM PRODUCT P
EXCEPT
SELECT S.ID_PRODUCT
FROM SALES_ITEMS S

-- 5
SELECT P.DESCRIPTION AS NAME
     , 'PRODUCT' AS TYPES
FROM PRODUCT P
UNION
SELECT C.NAME_CATEGORY
     , 'CATEGORY' AS TYPES
FROM CATEGORY C
UNION
SELECT S.LEGAL_NAME
     , 'SUPPLIER' AS TYPES
FROM SUPPLIER S
ORDER BY 1,2