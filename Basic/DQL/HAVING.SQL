-- 1
SELECT P.ID_CATEGORY
     , COUNT(P.ID_PRODUCT) AS TOTAL_PRODUCT
FROM PRODUCT P
GROUP BY P.ID_CATEGORY
HAVING COUNT(P.ID_PRODUCT) > 1

-- 2
SELECT SI.ID_PRODUCT
     , SUM(SI.QUANTITY) AS SUM_TOTAL
FROM SALES_ITEMS SI
GROUP BY SI.ID_PRODUCT
HAVING SUM(SI.QUANTITY) > 2

-- 3
SELECT PR.ID_SUPPLIER
     , AVG(PR.PRICE) AS AVG_PRICE
FROM PRODUCT PR
GROUP BY PR.ID_SUPPLIER
HAVING AVG(PR.PRICE) > 6

-- 4
SELECT S.ID_PRODUCT
     , SUM(S.QUANTITY  * S.UNIT_PRICE) AS SUBTOTAL
FROM SALES_ITEMS S
GROUP BY S.ID_PRODUCT
HAVING SUM(S.QUANTITY  * S.UNIT_PRICE) > 10
ORDER BY SUBTOTAL DESC

-- 5
UPDATE PRODUCT
    SET MIN_STOCK = 10
    WHERE ID_PRODUCT = 2

UPDATE PRODUCT
    SET MIN_STOCK = 7
    WHERE ID_PRODUCT = 3

SELECT PRO.ID_SUPPLIER
     , SUM(PRO.MIN_STOCK) AS SUM_STOCK_MIN
     , MAX(PRICE) AS MAX_PRICE
FROM PRODUCT PRO
WHERE PRO.PRICE > 0
GROUP BY PRO.ID_SUPPLIER
HAVING SUM(PRO.MIN_STOCK) > 0
