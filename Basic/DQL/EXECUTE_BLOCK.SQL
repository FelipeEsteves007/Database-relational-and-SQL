EXECUTE BLOCK
AS
    DECLARE VARIABLE V_MAX_INSTALLMENTS INTEGER;
    DECLARE VARIABLE V_CURRENT_INSTALLMENT INTEGER;
    DECLARE VARIABLE V_TOTAL_SALE NUMERIC (10,2);
    DECLARE VARIABLE V_INSTALLMENT_VALUE NUMERIC (10,2);
BEGIN
  V_MAX_INSTALLMENTS = 4;
  V_CURRENT_INSTALLMENT = 1;
  V_TOTAL_SALE = 1000;
  v_installment_value = 0;

  WHILE (V_CURRENT_INSTALLMENT <= V_MAX_INSTALLMENTS) DO
  BEGIN

    V_INSTALLMENT_VALUE = V_TOTAL_SALE / V_MAX_INSTALLMENTS;

    IF (V_CURRENT_INSTALLMENT = V_MAX_INSTALLMENTS) THEN
    BEGIN
        V_INSTALLMENT_VALUE = V_INSTALLMENT_VALUE + 5.0;
    END

    V_CURRENT_INSTALLMENT = V_CURRENT_INSTALLMENT + 1;
  END
END;

