    DECLARE VARIABLE V_NAME VARCHAR(100);
BEGIN
    V_PRICE = 10.00;
    V_NAME = 'FELIPE';
END

-- 2
EXECUTE BLOCK
AS
    DECLARE VARIABLE V_NAME VARCHAR(100);
BEGIN
    SELECT P.DESCRIPTION
    FROM PRODUCT P
    WHERE P.ID_PRODUCT = 1
    INTO V_NAME;
END;

-- 3
EXECUTE BLOCK
AS
    DECLARE VARIABLE V_PRICE NUMERIC(10,2);
    DECLARE VARIABLE V_DISCOUNT NUMERIC(10,2);
    DECLARE VARIABLE V_TOTAL NUMERIC(10,2);
BEGIN
    V_PRICE = 10;
    V_DISCOUNT = 1;
    V_TOTAL = V_PRICE - V_DISCOUNT;
END

-- 4
EXECUTE BLOCK
AS
    DECLARE VARIABLE V_FIRST_NAME VARCHAR(100);
    DECLARE VARIABLE V_LAST_NAME VARCHAR(100);
    DECLARE VARIABLE V_FULL_NAME VARCHAR(100);
BEGIN
    V_FIRST_NAME = 'FELIPE';
    V_LAST_NAME = 'ESTEVES';
    V_FULL_NAME = V_FIRST_NAME || V_LAST_NAME;
END;

-- 5
EXECUTE BLOCK
AS
    DECLARE VARIABLE V_UNIT_PRICE NUMERIC(10,2);
    DECLARE VARIABLE V_STOCK INTEGER;
    DECLARE VARIABLE V_TOTAL_VALUE NUMERIC(10,2);
BEGIN
    SELECT P.MIN_STOCK, P.PRICE
    FROM PRODUCT P
    WHERE P.ID_PRODUCT = 1
    INTO V_STOCK, V_UNIT_PRICE;

    V_TOTAL_VALUE = V_STOCK * V_UNIT_PRICE;
END;  