EXECUTE BLOCK
AS
    DECLARE VARIABLE V_UNIT_PRICE NUMERIC(10,2);
    DECLARE VARIABLE V_STOCK INTEGER;
    DECLARE VARIABLE V_TOTAL_VALUE NUMERIC(10,2);
BEGIN
    SELECT P.MIN_STOCK, P.PRICE
    FROM PRODUCT P
    WHERE P.ID_PRODUCT = 1
    INTO V_STOCK, V_UNIT_PRICE;

    V_TOTAL_VALUE = V_STOCK * V_UNIT_PRICE;
END; 

-- 6
EXECUTE BLOCK
AS
    DECLARE VARIABLE V_TOTAL NUMERIC(10,2);
    DECLARE VARIABLE V_SITUATION VARCHAR(100);
BEGIN
    SELECT S.TOTAL
    FROM SALES S
    WHERE S.ID_SALE = 1
    INTO V_TOTAL;

    IF (V_TOTAL > 100) THEN
    BEGIN
        V_SITUATION = 'VIP';
    END
    ELSE
    BEGIN   
        IF (V_TOTAL  > 50 AND V_TOTAL < 100) THEN
        BEGIN
            V_SITUATION = 'REGULAR';
        END
        ELSE
        BEGIN
            V_SITUATION = 'BASIC';
        END
    END
END

