EXECUTE BLOCK
AS
    DECLARE VARIABLE V_TOTAL_HIGH NUMERIC(10,2);
    DECLARE VARIABLE V_TOTAL_LOW NUMERIC(10,2);
    DECLARE VARIABLE V_COUNT_PROD INTEGER;
    DECLARE VARIABLE V_ID INTEGER;
    DECLARE VARIABLE V_PRICE NUMERIC(10,2);
BEGIN
    V_TOTAL_HIGH = 0.0;
    V_TOTAL_LOW  = 0.0;
    V_COUNT_PROD = 0;
    V_ID         = 0;
    V_PRICE      = 0.0;

    FOR SELECT P.ID_PRODUCT, P.PRICE
    FROM PRODUCT P
    INTO :V_ID, :V_PRICE
    DO
    BEGIN

        IF (V_PRICE > 50) THEN
        BEGIN
            V_TOTAL_HIGH = V_TOTAL_HIGH + V_PRICE;
        END
        ELSE
        BEGIN
            IF (V_PRICE < 50) THEN
            BEGIN
                V_TOTAL_LOW = V_TOTAL_LOW + V_PRICE;
            END
        END
    V_COUNT_PROD = V_COUNT_PROD + 1;
    END 
END;