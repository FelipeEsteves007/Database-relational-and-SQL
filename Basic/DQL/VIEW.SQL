CREATE VIEW VW_CATEGORY_UPPER AS
SELECT UPPER(C.NAME_CATEGORY) AS UPPER_CATEGORY
FROM CATEGORY C

SELECT * FROM VW_CATEGORY_UPPER

-- 2
CREATE VIEW VW_SALE_SUMARY AS
SELECT S.ID_SALE
     , SA.ID_PRODUCT
     , (SA.QUANTITY  * SA.UNIT_PRICE) AS SUBTOTAL
     , S.DATE_SALE
FROM SALES S
INNER JOIN SALES_ITEMS SA ON S.ID_SALE = SA.ID_SALE

SELECT * FROM VW_SALE_SUMARY

-- 3
SELECT ID_SALE, SUBTOTAL FROM VW_SALE_SUMARY WHERE SUBTOTAL > 100

-- 4
RECREATE VIEW VW_SALE_SUMARY AS
SELECT S.ID_SALE
     , SA.ID_PRODUCT
     , (SA.QUANTITY  * SA.UNIT_PRICE) AS SUBTOTAL
     , S.DATE_SALE
     , SA.UNIT_PRICE
     , SA.QUANTITY
FROM SALES S
INNER JOIN SALES_ITEMS SA ON S.ID_SALE = SA.ID_SALE

-- 5
CREATE VIEW VW_CATEGORY_INVOICING AS
SELECT C.NAME_CATEGORY
     , SUM(S.UNIT_PRICE * S.QUANTITY) AS INVOICING
FROM CATEGORY C
INNER JOIN PRODUCT P ON C.ID_CATEGORY = P.ID_CATEGORY
INNER JOIN SALES_ITEMS S ON P.ID_PRODUCT = S.ID_PRODUCT
GROUP BY C.NAME_CATEGORY