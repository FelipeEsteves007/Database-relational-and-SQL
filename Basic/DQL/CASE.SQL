-- 1
SELECT P.DESCRIPTION
     , P.PRICE
     , CASE
         WHEN P.PRICE > 50 THEN 'EXPENSIVE'
         ELSE 'CHEAP'
        END AS STATUS
FROM PRODUCT P

-- 2
SELECT P.DESCRIPTION
     , P.MIN_STOCK
     , CASE
        WHEN P.MIN_STOCK < 5 THEN 'CRITICAL'
        WHEN P.MIN_STOCK BETWEEN 5 AND 10 THEN 'WARNING'
        ELSE 'SAFE'
       END AS STOCK
FROM PRODUCT P

-- 3
SELECT P.DESCRIPTION
     , CASE
        WHEN C.NAME_CATEGORY IS NULL THEN 'NO CATEGORY'
        ELSE C.NAME_CATEGORY
       END AS NAME_CATEGORY /* COALESCE(C.NAME_CATEGORY, 'NO CATEGORY') */
FROM PRODUCT P
LEFT JOIN CATEGORY C ON P.ID_CATEGORY = C.ID_CATEGORY

-- 4
SELECT SI.ID_PRODUCT
     , SI.QUANTITY
     , CASE
        WHEN SI.QUANTITY > 5 THEN SI.UNIT_PRICE * 0.90
        ELSE SI.UNIT_PRICE
       END AS DISCOUNT
FROM SALES_ITEMS SI

-- 5
SELECT SI.ID_PRODUCT
     , SUM (CASE
              WHEN SI.QUANTITY <= 5 THEN SI.QUANTITY
              ELSE 0
            END) AS "TOTAL V"
     , SUM (CASE
              WHEN SI.QUANTITY > 5 THEN SI.QUANTITY
              ELSE 0
            END) AS "TOTAL A"
FROM SALES_ITEMS SI
GROUP BY SI.ID_PRODUCT