-- 1
SELECT 'PRODUCT: ' || P.description || ', PRICE: ' || P.price
FROM PRODUCT P

-- 2
SELECT S.ID_CLIENT
     , EXTRACT(MONTH FROM S.DATE_SALE) AS MONTH_DATE
FROM SALES S
WHERE EXTRACT(MONTH FROM S.DATE_SALE) = 8

-- 3
SELECT P.DESCRIPTION
     , CAST((P.MIN_STOCK * 2) AS NUMERIC(2,1))  AS MIN_STOCK
FROM PRODUCT P

-- 4
SELECT UPPER(C.NAME_CATEGORY) AS CATEGORY_NAME
     , UPPER(SUBSTRING(C.NAME_CATEGORY FROM 1 FOR 3)) AS CATEGORY_NAME_3
FROM CATEGORY C

-- 5
SELECT EXTRACT(DAY FROM S.DATE_SALE) AS DAY_SALE
     , EXTRACT(MONTH FROM S.DATE_SALE) AS MONTH_SALE
     , EXTRACT(YEAR FROM S.DATE_SALE) AS YEAR_SALE
     , 'SALE COMPLETED ON ' || CAST(EXTRACT(MONTH FROM S.DATE_SALE) AS VARCHAR(2))|| ' AND ' || CAST(EXTRACT(DAY FROM S.DATE_SALE) AS VARCHAR(2))
     , (CAST(ST.UNIT_PRICE AS NUMERIC(10,2))) AS SUBTOTAL
FROM SALES S
INNER JOIN SALES_ITEMS ST ON S.ID_SALE = ST.ID_SALE