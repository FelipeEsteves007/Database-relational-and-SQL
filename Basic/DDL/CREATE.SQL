-- 1
CREATE TABLE PRODUCT (
    ID_PRODUCT INTEGER PRIMARY KEY NOT NULL,
    DESCRIPTION VARCHAR(50)
)

-- 2
CREATE TABLE CATEGORY (
    ID_CATEGORY INTEGER PRIMARY KEY NOT NULL,
    NAME_CATEGORY VARCHAR(30),
    DATE_CREATION DATE
)

-- 3
CREATE TABLE EMPLOYEE (
    ID_EMPLOYEE INTEGER PRIMARY KEY NOT NULL,
    NAME_FULL VARCHAR(100),
    WAGE NUMERIC(15,2),
    DATE_HIRE DATE
)

-- 4
CREATE TABLE SALES (
    ID_SALE INTEGER PRIMARY KEY NOT NULL,
    DATE_SALE DATE,
    TOTAL NUMERIC(15,2) NOT NULL
)

-- 5
CREATE TABLE SUPPLIER (
    ID_SUPPLIER INTEGER PRIMARY KEY NOT NULL,
    DOCUMENT VARCHAR(14) NOT NULL UNIQUE,
    LEGAL_NAME VARCHAR(100)
)

